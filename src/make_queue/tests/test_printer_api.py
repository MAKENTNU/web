import socket
from unittest import mock

from django.core.exceptions import ValidationError
from django.core.files.uploadedfile import SimpleUploadedFile
from django.test import SimpleTestCase

from make_queue.printer_api import (
    OFFLINE_STATE,
    PrinterError,
    get_base_url,
    get_print_state,
    looks_like_gcode,
    resolve_printer_address,
    validate_printer_address,
)


def fake_getaddrinfo(*ips: str):
    return mock.Mock(
        return_value=[
            (socket.AF_INET6 if ":" in ip else socket.AF_INET, None, None, "", (ip, 0))
            for ip in ips
        ]
    )


class TestValidatePrinterAddress(SimpleTestCase):
    def test_ip_addresses_and_hostnames_are_valid(self):
        for address in (
            "100.64.0.1",
            "192.168.1.20",
            "fd7a:115c:a1e0::1",
            "printer-1",
            "printer-1.tail1234.ts.net",
        ):
            with self.subTest(address=address):
                validate_printer_address(address)

    def test_invalid_addresses_are_rejected(self):
        for address in (
            "http://100.64.0.1",
            "100.64.0.1:80",
            "printer 1",
            "-printer",
            "printer_1",
            "printer.local/",
        ):
            with self.subTest(address=address), self.assertRaises(ValidationError):
                validate_printer_address(address)


class TestResolvePrinterAddress(SimpleTestCase):
    def test_local_and_tailscale_ips_are_allowed(self):
        for ip in ("100.64.0.1", "100.127.255.254", "192.168.1.20", "10.0.0.5"):
            with self.subTest(ip=ip):
                self.assertEqual(resolve_printer_address(ip), ip)

    def test_other_ips_are_rejected(self):
        for ip in (
            "8.8.8.8",  # On the internet
            "127.0.0.1",  # The server itself
            "::1",  # The server itself
            "169.254.169.254",  # Cloud metadata services
            "100.128.0.1",  # Just outside Tailscale's range
        ):
            with self.subTest(ip=ip), self.assertRaises(PrinterError):
                resolve_printer_address(ip)

    def test_hostname_is_resolved_and_checked(self):
        with mock.patch("socket.getaddrinfo", fake_getaddrinfo("100.101.102.103")):
            self.assertEqual(resolve_printer_address("printer-1"), "100.101.102.103")

        # Rejected if any of the resolved IPs are disallowed
        with (
            mock.patch("socket.getaddrinfo", fake_getaddrinfo("100.64.0.1", "8.8.8.8")),
            self.assertRaises(PrinterError),
        ):
            resolve_printer_address("printer-1")

    def test_unknown_hostname_raises_printer_error(self):
        with (
            mock.patch("socket.getaddrinfo", side_effect=socket.gaierror("not found")),
            self.assertRaises(PrinterError),
        ):
            resolve_printer_address("printer-1")

    def test_empty_address_raises_printer_error(self):
        with self.assertRaises(PrinterError):
            resolve_printer_address("")

    def test_ipv6_addresses_are_enclosed_in_brackets_in_urls(self):
        self.assertEqual(get_base_url("fd7a:115c:a1e0::1"), "http://[fd7a:115c:a1e0::1]")
        self.assertEqual(get_base_url("100.64.0.1"), "http://100.64.0.1")


class TestGetPrintState(SimpleTestCase):
    @mock.patch("make_queue.printer_api.requests.get")
    def test_returns_state_from_printer(self, get_mock):
        get_mock.return_value.json.return_value = {
            "result": {"status": {"print_stats": {"state": "printing"}}}
        }
        self.assertEqual(get_print_state("100.64.0.1"), "printing")

    @mock.patch("make_queue.printer_api.requests.get")
    def test_returns_offline_on_unexpected_response(self, get_mock):
        get_mock.return_value.json.return_value = {"error": "something"}
        self.assertEqual(get_print_state("100.64.0.1"), OFFLINE_STATE)

    @mock.patch("make_queue.printer_api.requests.get")
    def test_returns_offline_for_disallowed_address_without_contacting_it(
        self, get_mock
    ):
        self.assertEqual(get_print_state("8.8.8.8"), OFFLINE_STATE)
        get_mock.assert_not_called()


class TestLooksLikeGcode(SimpleTestCase):
    def test_gcode_is_accepted(self):
        content = (
            b"; generated by PrusaSlicer\n\nM73 P0 R12\nG28\nT0\nG1 X10 Y10 F3000\n"
        )
        self.assertTrue(looks_like_gcode(SimpleUploadedFile("a.gcode", content)))

    def test_other_files_are_rejected(self):
        for content in (
            b"",
            b"solid benchy\nfacet normal 0 0 1\nouter loop\n",
            b"\x00\x01\x02binary",
        ):
            with self.subTest(content=content):
                self.assertFalse(
                    looks_like_gcode(SimpleUploadedFile("a.gcode", content))
                )
